"""Prepare WebP release assets without changing any source artwork.

Requires Pillow with WebP support. Output and cache are disposable, separate
directories. A content/version/settings cache makes subsequent runs inexpensive.
"""
from concurrent.futures import ThreadPoolExecutor
import argparse
import hashlib
import io
import json
from pathlib import Path
import sys
import PIL
from PIL import Image, features

ROOT = Path(__file__).resolve().parents[1]
SETTINGS = {'quality': 90, 'method': 6, 'exact': True, 'alpha_quality': 100}

def sha(data):
    return hashlib.sha256(data).hexdigest()

def write_changed(path, data):
    if path.exists() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)

def prepare(source, output, cache, workers=4):
    source, output, cache = source.resolve(), output.resolve(), cache.resolve()
    roots = [source, output, cache]
    if any(a == b or a.is_relative_to(b) or b.is_relative_to(a) for i,a in enumerate(roots) for b in roots[i+1:]):
        raise ValueError('Source, output and cache must be separate directories')
    if not source.is_dir():
        raise ValueError('Source directory does not exist')
    if not features.check('webp'):
        raise ValueError('Pillow needs WebP encoder support')
    marker = output / '.prepared-assets'
    if output.exists() and any(output.iterdir()) and not marker.is_file():
        raise ValueError('Refusing to alter an unmanaged output directory')
    output.mkdir(parents=True, exist_ok=True); cache.mkdir(parents=True, exist_ok=True)
    write_changed(marker,b'Generated by scripts/prepare-assets.py\n')
    encoder = {'pillow': PIL.__version__, 'webp': features.version('webp')}
    signature = json.dumps({'version': 1, 'settings': SETTINGS, 'encoder': encoder}, sort_keys=True)
    sources = sorted(p for p in source.rglob('*') if p.is_file() and not p.name.endswith('.prompt.txt'))
    expected = {'.prepared-assets', 'asset-manifest.json'}

    def convert(path):
        relative = path.relative_to(source).as_posix()
        data = path.read_bytes(); source_hash = sha(data)
        image = path.suffix.lower() == '.png'
        target_relative = str(Path(relative).with_suffix('.webp')).replace('\\', '/') if image else relative
        target = output / target_relative
        if not target.resolve().is_relative_to(output):
            raise ValueError('Output asset escapes its managed directory')
        if not image:
            write_changed(target, data)
            return target_relative, None, len(data)
        key = sha((signature + relative + source_hash).encode('utf-8'))
        cached = cache / (key + '.webp')
        with Image.open(io.BytesIO(data)) as original:
            rgba = original.convert('RGBA')
            width, height = rgba.size
            if cached.is_file():
                encoded = cached.read_bytes()
            else:
                buffer = io.BytesIO()
                options = dict(SETTINGS)
                if original.info.get('icc_profile'):
                    options['icc_profile'] = original.info['icc_profile']
                rgba.save(buffer, format='WEBP', **options)
                encoded = buffer.getvalue()
                write_changed(cached, encoded)
            # Lossy RGB is allowed; alpha and original dimensions must be exact.
            with Image.open(io.BytesIO(encoded)) as decoded:
                if decoded.size != rgba.size or decoded.convert('RGBA').getchannel('A').tobytes() != rgba.getchannel('A').tobytes():
                    raise ValueError('WebP must preserve image dimensions and alpha: ' + relative)
        write_changed(target, encoded)
        return target_relative, {'source': relative, 'output': target_relative, 'sourceSha256': source_hash,
            'sha256': sha(encoded), 'sourceBytes': len(data), 'outputBytes': len(encoded),
            'width': width, 'height': height}, len(data)

    with ThreadPoolExecutor(max_workers=workers) as pool:
        converted = list(pool.map(convert, sources))
    for relative, _, _ in converted:
        expected.add(relative)
    # Only this marked, fully managed output is cleaned; source and cache remain untouched.
    for path in sorted(output.rglob('*'), reverse=True):
        if path.is_symlink():
            raise ValueError('Symlinks are not allowed in generated assets')
        if path.is_file() and path.relative_to(output).as_posix() not in expected:
            if not path.resolve().is_relative_to(output):
                raise ValueError('Stale asset escapes managed output')
            path.unlink()
        elif path.is_dir() and not any(path.iterdir()):
            path.rmdir()
    images = [entry for _,entry,_ in converted if entry]
    manifest = {'version': 1, 'encoder': encoder, 'settings': SETTINGS, 'images': images}
    write_changed(output / 'asset-manifest.json', (json.dumps(manifest,ensure_ascii=False,indent=2)+'\n').encode('utf-8'))
    total = sum(p.stat().st_size for p in output.rglob('*') if p.is_file())
    return {'images': len(images), 'sourceBytes': sum(size for _,_,size in converted), 'preparedBytes': total,
        'imageSourceBytes': sum(e['sourceBytes'] for e in images), 'imagePreparedBytes': sum(e['outputBytes'] for e in images)}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,default=ROOT/'public')
    parser.add_argument('--output',type=Path,default=ROOT/'.generated'/'public')
    parser.add_argument('--cache',type=Path,default=ROOT/'.generated'/'image-cache')
    parser.add_argument('--workers',type=int,default=4)
    args = parser.parse_args()
    if args.workers < 1 or args.workers > 16:
        parser.error('workers must be 1..16')
    print(json.dumps(prepare(args.source,args.output,args.cache,args.workers),ensure_ascii=False))

if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError) as error:
        print(str(error),file=sys.stderr);sys.exit(1)
