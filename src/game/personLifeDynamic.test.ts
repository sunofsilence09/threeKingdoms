import { describe, expect, it } from 'vitest';
import { createInitialState } from './state';
import { createProgress } from './growth';
import { prefectIdentity } from './prefectIdentity';
import { PERSON_LIFE_BASELINES } from './personLifeData';
import { createLifeState, ensureLifePeople, isLifeState, lifeBaseline, lifeLabel, lifeStatus, reconcileLives, repairLifeState } from './personLife';

const id='prefect-chenliu-han-184-1';
const id2='prefect-shanyin-sun-200-2';
const date=(year:number)=>({year,month:1,day:1});
describe('persistent original prefect lives',()=>{
  it('derives only valid original IDs and fills missing people without changing any saved draw',()=>{
    expect(lifeBaseline(id)).toEqual(prefectIdentity(id)!.baseline);
    expect(lifeBaseline('prefect-fake-han-184-1')).toBeUndefined();
    const life=createLifeState(date(184),43),before=structuredClone(life);
    life.people['cao-cao'].deathYear=225;
    const next=ensureLifePeople(life,[id,id,'unknown','prefect-chenliu-fake-184-1']);
    expect(Object.keys(next.people)).toHaveLength(PERSON_LIFE_BASELINES.length+1);
    expect(next.people['cao-cao'].deathYear).toBe(225);
    for(const p of PERSON_LIFE_BASELINES.filter(p=>p.id!=='cao-cao'))expect(next.people[p.id]).toEqual(before.people[p.id]);
    expect(life.people[id]).toBeUndefined();
    expect(next.seed).toBe(43);
    expect(next.notices).toEqual([]);
    expect(ensureLifePeople(next,[id])).toBe(next);
    expect(isLifeState(next,date(184))).toBe(true);
  });
  it('queries missing generated entries using the same seed and never mutates on a query',()=>{
    const life=createLifeState(date(184),43),before=structuredClone(life);
    const populated=ensureLifePeople(life,[id]);
    const death=populated.people[id].deathYear;
    expect(lifeStatus(life,id,date(death-1))).toBe('alive');
    expect(lifeStatus(life,id,date(death))).toBe('dead');
    expect(lifeLabel(life,id,date(death))).toContain(`于${death}年`);
    expect(lifeLabel(life,id,date(184))).toContain('游戏人物');
    expect(life).toEqual(before);
    expect(ensureLifePeople(JSON.parse(JSON.stringify(life)),[id]).people[id]).toEqual(populated.people[id]);
  });
  it('silently handles newly registered past deaths and restores missing static additions',()=>{
    const life=createLifeState(date(300),43);
    delete life.people['dian-wei'];
    const next=ensureLifePeople(life,[id]);
    expect(next.people['dian-wei']).toBeDefined();
    expect(next.handledIds).toContain(id);
    expect(next.notices).toEqual([]);
    expect(isLifeState(next,date(300))).toBe(true);
    expect(isLifeState({...next,people:{...next.people,unknown:{birthYear:150,deathYear:220}}})).toBe(false);
    expect(isLifeState({...next,handledIds:next.handledIds.filter(x=>x!==id)})).toBe(false);
    expect(isLifeState({...next,people:{...next.people,[id]:{...next.people[id],birthYear:0}}})).toBe(false);
  });
  it('preserves dynamic records and complete memorial evidence during module repair',()=>{
    const state=createInitialState(()=>0),life=ensureLifePeople(createLifeState(date(184),43),[id,id2]);
    const baseline=lifeBaseline(id)!;
    life.people[id].deathYear=baseline.deathBaseYear-5;
    const now=date(baseline.deathBaseYear-4),progress=createProgress(5,13),relationship={affinity:97,lastInteraction:3000};
    const archived=reconcileLives({...state,date:now,life,party:{...state.party,[id]:progress},relationships:{...state.relationships,[id]:relationship}},now);
    const before=structuredClone(archived.life!),damaged=structuredClone(before);
    damaged.people[id].deathYear=baseline.deathBaseYear+5;
    damaged.people['cao-cao'].birthYear=0;
    const recovered=repairLifeState(damaged,now)!;
    expect(recovered.life.people[id]).toEqual(before.people[id]);
    expect(recovered.life.people[id2]).toEqual(before.people[id2]);
    expect(recovered.life.memorials[id]).toEqual(before.memorials[id]);
    expect(recovered.life.memorials[id].progress).toEqual(progress);
    expect(lifeStatus(recovered.life,id,now)).toBe('dead');
    expect(isLifeState(recovered.life,now)).toBe(true);
    expect(repairLifeState(recovered.life,now)).toEqual({life:recovered.life,repaired:false});
    const lost=structuredClone(damaged); delete lost.people[id];
    expect(repairLifeState(lost,now)!.life.people[id]).toEqual(before.people[id]);
  });
  it('discovers party and governor IDs, archives death once, and keeps strategic state untouched',()=>{
    const state=createInitialState(()=>0),life=createLifeState(date(184),43);
    const generated=ensureLifePeople(life,[id]),death=generated.people[id].deathYear,progress=createProgress(4,5);
    const world={...state.worldConflict!,cities:{...state.worldConflict!.cities,shanyin:{...state.worldConflict!.cities.shanyin,governorId:id2}}};
    const before={...state,date:date(death-1),life,worldConflict:world,party:{...state.party,[id]:progress},relationships:{...state.relationships,[id]:{affinity:90}},deployed:['traveler',id],battleParty:['traveler',id]};
    const next=reconcileLives(before,date(death));
    expect(next.life!.people[id2]).toBeDefined();
    expect(next.life!.memorials[id]).toMatchObject({id,deathYear:death,progress});
    expect(next.party[id]).toBeUndefined();
    expect(next.relationships[id]).toBeUndefined();
    expect(next.deployed).toEqual(['traveler']);
    expect(next.battleParty).toEqual(['traveler']);
    expect(next.worldConflict).toBe(world);
    expect(next.economy).toBe(before.economy);
    expect(next.life!.notices.filter(n=>n.id===id)).toHaveLength(1);
    expect(reconcileLives(next,date(death))).toBe(next);
    expect(isLifeState(next.life,date(death))).toBe(true);
  });
  it('silently handles unowned original officials without crowding out owned death notices',()=>{
    const state=createInitialState(()=>0),life=ensureLifePeople(createLifeState(date(184),43),[id]);
    const death=life.people[id].deathYear;
    const before={...state,date:date(death-1),life};
    const next=reconcileLives(before,date(death));
    expect(next.life!.handledIds).toContain(id);
    expect(next.life!.notices.some(n=>n.id===id)).toBe(false);
    expect(life.handledIds).not.toContain(id);
    expect(life.notices).toEqual([]);
  });
  it('appends the 32-person catalog to a real old-size life module without redrawing its 73 records',()=>{
    const saved=createLifeState(date(250),43);
    const oldIds=PERSON_LIFE_BASELINES.slice(0,73).map(p=>p.id);
    const oldPeople=Object.fromEntries(oldIds.map(id=>[id,saved.people[id]]));
    oldPeople['cao-cao']={birthYear:155,deathYear:225};
    const old={...saved,people:oldPeople,handledIds:saved.handledIds.filter(id=>oldIds.includes(id))};
    const next=ensureLifePeople(old,[id]);
    expect(Object.keys(next.people)).toHaveLength(113);
    for(const [key,person] of Object.entries(oldPeople)) expect(next.people[key]).toEqual(person);
    expect(next.seed).toBe(old.seed);
    expect(next.notices).toEqual(old.notices);
    expect(isLifeState(next,date(250))).toBe(true);
    const damaged={...next,seed:-1,people:{...next.people,[id]:{...next.people[id],birthYear:0},[id2]:ensureLifePeople(old,[id2]).people[id2],unknown:{birthYear:150,deathYear:220}}};
    const repaired=repairLifeState(damaged,date(250))!.life;
    for(const [key,person] of Object.entries(oldPeople))expect(repaired.people[key]).toEqual(person);
    expect(repaired.people[id2]).toEqual(damaged.people[id2]);
    expect(repaired.people.unknown).toBeUndefined();
    expect(isLifeState(repaired,date(250))).toBe(true);
  });
});
